-- Questions:

-- 1. Display all records from the customer table.
select * from customers;

-- 2. Display the names and cities of all customers who live in lucknow.
select customer_name from customers where city='lucknow';

-- 3. Find all products whose selling price is greater than 2000.
select product_name from products where selling_price>2000;

-- 4. Display all products in descending order of selling price.
select product_name,selling_price from products order by selling_price desc;

-- 5. Find the 5 cheapest products.
select * from products order by selling_price asc limit 5;

-- 6. Count the total number of customers.
select count(customer_name) from customers;

-- 7. Find the average selling price of all products.
select avg(selling_price) from products;

-- 8. Find the maximun and minimum selling price.
select max(selling_price) from products;
select min(selling_price) from products;

-- 9. Count how many products belong to each product category.
select product_category, count(*) as Total_Products from products group by product_category;

-- 10. Find the total quantity ordered for each product id.
select product_id, sum(quantity) as Total_Quantity from orders group by product_id;

-- 11. Calculate the total revenue generated by each product category. Include only completed orders and sort categories by revenue from highest to lowest.
select products.product_category,sum(products.selling_price*orders.quantity) as Total_Revenue 
from products inner join orders on products.product_id= orders.product_id where orders.status='Completed' 
group by products. product_category order by Total_Revenue desc;

-- 12. Find the top 5 customers based on their total spending on completed orders. Display customer name, city, and total spending.
select customers.customer_name,customers.city,sum(products.selling_price*orders.quantity) as Total_Spending from customers inner join 
orders on customers.customer_id=orders.customer_id inner join products on orders.product_id=products.product_id  where orders.status='Completed' 
group by customers.customer_id,customers.customer_name,customers.city order by Total_Spending desc limit 5;

-- 13. Find all products that have never been ordered. Display the product ID, product name, and category.
select products.product_id,products.product_name,products.product_category from products left join orders 
on products.product_id=orders.product_id where orders.product_id is null;

-- 14. Calculate the total revenue for each month in 2025 from completed orders, arranged chronologically.
select month(order_date) as Month_Number, monthname(order_date) as Month_Name, sum(products.selling_price*orders.quantity) 
as Total_Revenue from orders inner join products on orders.product_id= products.product_id where orders.status='Completed'and 
year(order_date)=2025 group by month(order_date),monthname(order_date) order by month(order_date);

-- 15.Find customers who have never placed a completed order, including customers with no orders at all.
